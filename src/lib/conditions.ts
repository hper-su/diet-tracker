// 動作チェックプロトコルを持つ項目(=お客様概要から症状ベースで選択できる項目)。
export const PROTOCOL_CONDITIONS = CONDITIONS.filter(
  (c): c is Condition & { protocolTable: ProtocolStep[]; symptomLabel: string } =>
    c.protocolTable != null && c.symptomLabel != null,
);

export function getProtocolCondition(conditionId: string) {
  return PROTOCOL_CONDITIONS.find((c) => c.id === conditionId);
}

export function searchConditions(query: string): Condition[] {
  const q = query.trim().toLowerCase();
  if (!q) return CONDITIONS;
  const haystack = (c: Condition) =>
    [
      c.name,
      ...c.precautions,
      ...c.doThis,
      ...c.redFlags,
      ...c.contraindications,
      ...c.medication,
      ...c.mentalCare,
      c.ageNote,
    ]
      .join(" ")
      .toLowerCase();
  return CONDITIONS.filter((c) => haystack(c).includes(q));
}

