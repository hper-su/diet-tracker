-- Realtime(端末間のリアルタイム同期)用に、全テーブルをpublicationへ追加する。
-- 既に追加済みの場合はエラーになるため、存在確認してから追加する。
do $$
declare
  t text;
begin
  foreach t in array array['clients', 'measurements', 'foods', 'mealLogs', 'usualMeals', 'exercises', 'usualExercises', 'protocolChecks']
  loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table %I', t);
    end if;
  end loop;
end $$;

-- データ管理画面(/data)からのインポート機能用: bulkインポートでidを明示指定して
-- 挿入した後、次回以降のauto-increment(identity)がその最大id以下から再開して
-- 重複してしまわないよう、各テーブルのシーケンスを現在の最大idに合わせ直す。
-- 匿名ロールにテーブルへの直接のシーケンス操作権限は与えていないため、
-- security definerな関数経由で実行する。
create or replace function reset_id_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  t text;
begin
  foreach t in array array['clients', 'measurements', 'foods', 'mealLogs', 'usualMeals', 'exercises', 'usualExercises', 'protocolChecks']
  loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from %I), 1))',
      quote_ident(t), t
    );
  end loop;
end;
$$;

grant execute on function reset_id_sequences() to anon, authenticated;

-- データ管理画面(/data)の「インポート」用: 全テーブルの削除→再投入を
-- 1回の関数呼び出し(=1トランザクション)にまとめる。クライアント側で
-- 複数回のAPI呼び出しに分けていた場合、途中の1回が失敗すると一部のテーブルだけ
-- 空になったまま残ってしまう(共有DBなので他端末にもその不完全な状態が
-- 見えてしまう)。関数内で例外が起きれば呼び出し全体が自動的にロールバックされる
-- ため、この不整合を防げる。
create or replace function import_all_data(payload jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from "protocolChecks";
  delete from "usualExercises";
  delete from "usualMeals";
  delete from "mealLogs";
  delete from measurements;
  delete from clients;
  delete from foods;
  delete from exercises;

  insert into clients (
    id, name, birthdate, "heightCm", gender, "activityLevel", "pfcPreset",
    "targetMonthlyWeightChangeKg", "targetWeightChangeKg", "targetPeriodMonths",
    "targetWeightKg", memo, "createdAt"
  )
  select
    id, name, birthdate, "heightCm", gender, "activityLevel", "pfcPreset",
    "targetMonthlyWeightChangeKg", "targetWeightChangeKg", "targetPeriodMonths",
    "targetWeightKg", memo, "createdAt"
  from jsonb_to_recordset(payload->'clients') as t(
    id integer, name text, birthdate text, "heightCm" double precision, gender text,
    "activityLevel" text, "pfcPreset" text,
    "targetMonthlyWeightChangeKg" double precision, "targetWeightChangeKg" double precision,
    "targetPeriodMonths" double precision, "targetWeightKg" double precision,
    memo text, "createdAt" timestamptz
  );

  insert into foods (id, category, name, "servingLabel", kcal, "proteinG", "fatG", "carbG")
  select id, category, name, "servingLabel", kcal, "proteinG", "fatG", "carbG"
  from jsonb_to_recordset(payload->'foods') as t(
    id integer, category text, name text, "servingLabel" text, kcal double precision,
    "proteinG" double precision, "fatG" double precision, "carbG" double precision
  );

  insert into exercises (id, category, name, mets)
  select id, category, name, mets
  from jsonb_to_recordset(payload->'exercises') as t(
    id integer, category text, name text, mets double precision
  );

  insert into measurements (
    id, "clientId", "recordedAt", "weightKg", "bodyFatPct", "muscleMassKg",
    "visceralFatLevel", "bmrKcal", memo
  )
  select
    id, "clientId", "recordedAt", "weightKg", "bodyFatPct", "muscleMassKg",
    "visceralFatLevel", "bmrKcal", memo
  from jsonb_to_recordset(payload->'measurements') as t(
    id integer, "clientId" integer, "recordedAt" text, "weightKg" double precision,
    "bodyFatPct" double precision, "muscleMassKg" double precision,
    "visceralFatLevel" double precision, "bmrKcal" double precision, memo text
  );

  insert into "mealLogs" (
    id, "clientId", "recordedAt", "mealType", "foodId", "foodName", quantity,
    kcal, "proteinG", "fatG", "carbG", memo
  )
  select
    id, "clientId", "recordedAt", "mealType", "foodId", "foodName", quantity,
    kcal, "proteinG", "fatG", "carbG", memo
  from jsonb_to_recordset(payload->'mealLogs') as t(
    id integer, "clientId" integer, "recordedAt" text, "mealType" text,
    "foodId" integer, "foodName" text, quantity double precision, kcal double precision,
    "proteinG" double precision, "fatG" double precision, "carbG" double precision, memo text
  );

  insert into "usualMeals" (
    id, "clientId", "mealType", "foodId", "foodName", quantity, kcal, "proteinG", "fatG", "carbG"
  )
  select
    id, "clientId", "mealType", "foodId", "foodName", quantity, kcal, "proteinG", "fatG", "carbG"
  from jsonb_to_recordset(payload->'usualMeals') as t(
    id integer, "clientId" integer, "mealType" text, "foodId" integer, "foodName" text,
    quantity double precision, kcal double precision, "proteinG" double precision,
    "fatG" double precision, "carbG" double precision
  );

  insert into "usualExercises" (
    id, "clientId", "exerciseId", "exerciseName", mets, "durationMin", "frequencyPerWeek"
  )
  select
    id, "clientId", "exerciseId", "exerciseName", mets, "durationMin", "frequencyPerWeek"
  from jsonb_to_recordset(payload->'usualExercises') as t(
    id integer, "clientId" integer, "exerciseId" integer, "exerciseName" text,
    mets double precision, "durationMin" double precision, "frequencyPerWeek" double precision
  );

  insert into "protocolChecks" (id, "clientId", "recordedAt", "conditionId", results, memo)
  select id, "clientId", "recordedAt", "conditionId", results, memo
  from jsonb_to_recordset(payload->'protocolChecks') as t(
    id integer, "clientId" integer, "recordedAt" text, "conditionId" text,
    results jsonb, memo text
  );

  perform reset_id_sequences();
end;
$$;

grant execute on function import_all_data(jsonb) to anon, authenticated;

