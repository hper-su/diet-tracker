-- diet-tracker: Supabase (Postgres) スキーマ
-- Supabaseダッシュボードの SQL Editor でこのファイルの内容をそのまま実行する。
-- ログイン認証なしで誰でも読み書きできる共有DBとして運用する前提のため、
-- RLSは有効にした上で「全操作を許可」するポリシーを付けている
-- (匿名キーがアプリのビルド成果物に埋め込まれて公開されるため、実質的な
-- アクセス制御はこのポリシーの範囲=ネットワーク到達可能な全員、になる)。

create table if not exists clients (
  id integer generated by default as identity primary key,
  name text not null,
  birthdate text,
  "heightCm" double precision,
  gender text,
  "activityLevel" text not null,
  "pfcPreset" text not null,
  "targetMonthlyWeightChangeKg" double precision,
  "targetWeightChangeKg" double precision,
  "targetPeriodMonths" double precision,
  "targetWeightKg" double precision,
  memo text,
  "createdAt" timestamptz not null default now()
);

create table if not exists measurements (
  id integer generated by default as identity primary key,
  "clientId" integer not null references clients(id) on delete cascade,
  "recordedAt" text not null,
  "weightKg" double precision,
  "bodyFatPct" double precision,
  "muscleMassKg" double precision,
  "visceralFatLevel" double precision,
  "bmrKcal" double precision,
  memo text
);
create index if not exists measurements_client_recorded_idx
  on measurements ("clientId", "recordedAt");

create table if not exists foods (
  id integer generated by default as identity primary key,
  category text not null,
  name text not null,
  "servingLabel" text not null,
  kcal double precision not null,
  "proteinG" double precision not null,
  "fatG" double precision not null,
  "carbG" double precision not null,
  unique (category, name)
);

create table if not exists "mealLogs" (
  id integer generated by default as identity primary key,
  "clientId" integer not null references clients(id) on delete cascade,
  "recordedAt" text not null,
  "mealType" text not null,
  "foodId" integer references foods(id) on delete set null,
  "foodName" text not null,
  quantity double precision not null,
  kcal double precision not null,
  "proteinG" double precision not null,
  "fatG" double precision not null,
  "carbG" double precision not null,
  memo text
);
create index if not exists meal_logs_client_recorded_idx
  on "mealLogs" ("clientId", "recordedAt");
create index if not exists meal_logs_food_idx on "mealLogs" ("foodId");

create table if not exists "usualMeals" (
  id integer generated by default as identity primary key,
  "clientId" integer not null references clients(id) on delete cascade,
  "mealType" text not null,
  "foodId" integer references foods(id) on delete set null,
  "foodName" text not null,
  quantity double precision not null,
  kcal double precision not null,
  "proteinG" double precision not null,
  "fatG" double precision not null,
  "carbG" double precision not null
);
create index if not exists usual_meals_client_idx on "usualMeals" ("clientId");
create index if not exists usual_meals_food_idx on "usualMeals" ("foodId");

create table if not exists exercises (
  id integer generated by default as identity primary key,
  category text not null,
  name text not null,
  mets double precision not null,
  unique (category, name)
);

create table if not exists "usualExercises" (
  id integer generated by default as identity primary key,
  "clientId" integer not null references clients(id) on delete cascade,
  "exerciseId" integer references exercises(id) on delete set null,
  "exerciseName" text not null,
  mets double precision not null,
  "durationMin" double precision not null,
  "frequencyPerWeek" double precision not null
);
create index if not exists usual_exercises_client_idx on "usualExercises" ("clientId");
create index if not exists usual_exercises_exercise_idx on "usualExercises" ("exerciseId");

create table if not exists "protocolChecks" (
  id integer generated by default as identity primary key,
  "clientId" integer not null references clients(id) on delete cascade,
  "recordedAt" text not null,
  "conditionId" text not null,
  results jsonb not null,
  memo text
);
create index if not exists protocol_checks_client_recorded_idx
  on "protocolChecks" ("clientId", "recordedAt");

